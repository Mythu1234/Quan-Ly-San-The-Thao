const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require('typescript');
const source=fs.readFileSync(path.join(__dirname,'../src/utils/bookingReceipt.ts'),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exportsObject={};
vm.runInNewContext(code,{exports:exportsObject,Intl,Date,require:()=>({createBookingReceiptImage:()=>null})});
const data={bookingCode:'DS00000069',paymentCode:'TT00000069',customerName:'Nguyễn Thị Mỹ Thu',customerPhone:'0324536785',sport:'Bóng chuyền',court:'Sân BC-01',date:'05/11/2026',time:'14:00 - 15:30',total:'225.000 VND'};
const html=exportsObject.renderBookingReceipt(data,new Date('2026-11-04T05:18:08Z'));
for(const value of Object.values(data))assert.ok(html.includes(value),`Receipt retains ${value}`);
assert.ok(html.includes('12:18:08'),'Issue time uses Vietnam time');
assert.ok(html.includes('<style>')&&html.includes('@media print'),'CSS included offline with print layout');
assert.ok(html.includes('window.print()'),'Downloaded receipt supports print / save PDF');
const hostile=exportsObject.renderBookingReceipt({...data,customerName:'<img src=x onerror=alert(1)>',court:'A & B "test"'});
assert.ok(!hostile.includes('<img src=x'),'Customer data cannot inject HTML');
assert.ok(hostile.includes('&lt;img src=x onerror=alert(1)&gt;'));
assert.ok(hostile.includes('A &amp; B &quot;test&quot;'));
console.log('PASS: receipt fields, Vietnamese text, Vietnam issue time, offline CSS, print layout and HTML escaping');

const imageSource=fs.readFileSync(path.join(__dirname,'../src/utils/bookingReceiptImage.ts'),'utf8');
const imageCode=ts.transpileModule(imageSource,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const drawn=[];
const context={font:'',measureText(value){return {width:value.length*7};},scale(){},beginPath(){},moveTo(){},arcTo(){},closePath(){},fill(){},fillRect(){},fillText(value,x,y){drawn.push({value,x,y});}};
const canvas={width:0,height:0,getContext:()=>context};
const imageExports={};
vm.runInNewContext(imageCode,{exports:imageExports,Intl,Date,document:{createElement:()=>canvas}});
imageExports.createBookingReceiptImage(data,new Date('2026-11-04T05:18:08Z'));
const drawnText=drawn.map(item=>item.value).join('\n');
for(const value of Object.values(data))assert.ok(drawnText.includes(value),`PNG retains ${value}`);
assert.ok(!drawnText.includes('In / Lưu PDF'),'PNG has no action buttons');
assert.ok(!drawnText.includes('Chọn “Lưu dưới dạng PDF”'),'PNG has no export instructions');
assert.equal(canvas.width,800);
assert.ok(drawn.every(item=>item.y>=0&&item.y<canvas.height/2),'All fields fit image height');
const shortHeight=canvas.height;
drawn.length=0;
const longName='Khách hàng có tên dài '.repeat(20);
imageExports.createBookingReceiptImage({...data,customerName:longName});
assert.ok(canvas.height>shortHeight,'Long names expand image instead of clipping');
assert.ok(drawn.every(item=>item.y>=0&&item.y<canvas.height/2),'Wrapped fields fit expanded image');
console.log('PASS: PNG receipt data, action-free image, 2x resolution and long-text wrapping');
